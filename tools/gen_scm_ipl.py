"""Generates src/scm_objects_ipl.h - the objects SA-MP's main.scm makes as the game starts, as a text IPL.

SA-MP (R3) serves its own main.scm from samp.saa; its INITIAL and INITIAL2 missions create 74 objects that
stand in every SA-MP world (cranes with their LODs, doors, portakabins, the searchlights of Area 51...). The
IPL comes from the samp-web project, which runs those missions and places the objects as the game does:

    cd samp-web && npx tsx tools/sampscm/ipl.mts scm_objects.ipl
    python tools/gen_scm_ipl.py <path to scm_objects.ipl>
"""
import os
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'scm_objects_ipl.h')


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    text = open(sys.argv[1], encoding='latin1').read().replace('\r\n', '\n')
    lines = ['/* Generated by tools/gen_scm_ipl.py from samp-web tools/sampscm/ipl.mts - do not edit. */', '',
             'static const char scm_objects_ipl[] =']
    for line in text.split('\n'):
        if line == '' : continue
        lines.append('    "' + line.replace('\\', '\\\\').replace('"', '\\"') + '\\r\\n"')
    lines[-1] += ';'
    open(OUT, 'w', encoding='ascii', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
