"""Generates src/marker_dff.h - the placeholder model shown instead of SA-MP effect objects.

The model is a double-sided octahedron (diamond) centred on the effect point, written as a
RenderWare 3.6 (0x1803FFFF) clump with the same chunk layout as the SA-MP effect DFFs.
It carries prelit vertex colours (with per-face shading baked in) and an untextured material;
the DLL fills in the colour per effect type at runtime.

Run:  python tools/gen_marker.py
"""
import math
import os
import struct

RW_VER = 0x1803FFFF
HEIGHT = 0.6        # top/bottom tip distance from the centre, metres
RADIUS = 0.35       # ring radius, metres
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'marker_dff.h')


def chunk(typ, payload):
    return struct.pack('<III', typ, len(payload), RW_VER) + payload


def build():
    top, bot = (0.0, 0.0, HEIGHT), (0.0, 0.0, -HEIGHT)
    ring = [(RADIUS * math.cos(a), RADIUS * math.sin(a), 0.0) for a in (0, math.pi / 2, math.pi, 3 * math.pi / 2)]
    faces = []
    for i in range(4):
        a, b = ring[i], ring[(i + 1) % 4]
        faces.append((top, a, b))
        faces.append((bot, b, a))

    light = (-0.3, -0.4, 0.87)      # fake sun used only to bake shading into the vertex colours
    ln = math.sqrt(sum(c * c for c in light)); light = tuple(c / ln for c in light)

    verts, normals, shade, tris = [], [], [], []
    for f in faces:
        u = [f[1][k] - f[0][k] for k in range(3)]
        v = [f[2][k] - f[0][k] for k in range(3)]
        n = (u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0])
        nl = math.sqrt(sum(c * c for c in n)); n = tuple(c / nl for c in n)
        if sum(n[k] * (f[0][k] + f[1][k] + f[2][k]) for k in range(3)) < 0:     # make normals point outwards
            n = tuple(-c for c in n)
        lit = 0.45 + 0.55 * max(0.0, sum(n[k] * light[k] for k in range(3)))
        base = len(verts)
        for p in f:
            verts.append(p); normals.append(n); shade.append(min(255, int(round(lit * 255))))
        tris.append((base, base + 1, base + 2))
        tris.append((base, base + 2, base + 1))     # back face: double-sided regardless of culling/winding

    nv, nt = len(verts), len(tris)
    flags = 0x02 | 0x04 | 0x08 | 0x10 | 0x20 | 0x40   # positions, textured, prelit, normals, light, modulate material colour
    fmt = flags | (1 << 16)                            # one UV set (all zero) like the original effect models

    g = struct.pack('<IIII', fmt, nt, nv, 1)
    prelit_off_in_g = len(g)
    g += b'\xff\xff\xff\xff' * nv                      # prelit colours, filled by the DLL
    g += b'\x00' * (8 * nv)                            # UVs
    for a, b, c in tris:
        g += struct.pack('<HHHH', b, a, 0, c)          # RW stream order: v2, v1, material, v3
    g += struct.pack('<4f', 0.0, 0.0, 0.0, max(HEIGHT, RADIUS))
    g += struct.pack('<II', 1, 1)
    for p in verts: g += struct.pack('<3f', *p)
    for n in normals: g += struct.pack('<3f', *n)

    mat_struct = struct.pack('<I4BIIfff', 0, 255, 255, 255, 255, 0, 0, 1.0, 1.0, 1.0)
    material = chunk(0x07, chunk(0x01, mat_struct) + chunk(0x03, b''))
    matlist = chunk(0x08, chunk(0x01, struct.pack('<Ii', 1, -1)) + material)

    idx = b''.join(struct.pack('<III', a, b, c) for a, b, c in tris)
    binmesh = chunk(0x50E, struct.pack('<III', 0, 1, nt * 3) + struct.pack('<II', nt * 3, 0) + idx)
    geom_struct = chunk(0x01, g)
    geometry = chunk(0x0F, geom_struct + matlist + chunk(0x03, binmesh))
    geomlist = chunk(0x1A, chunk(0x01, struct.pack('<I', 1)) + geometry)

    frame = struct.pack('<9f3fiI', 1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0, 0, -1, 0x00020003)
    framelist = chunk(0x0E, chunk(0x01, struct.pack('<I', 1) + frame) +
                      chunk(0x03, chunk(0x253F2FE, b'fx_marker')))
    atomic = chunk(0x14, chunk(0x01, struct.pack('<IIII', 0, 0, 5, 0)) + chunk(0x03, b''))
    clump = chunk(0x10, chunk(0x01, struct.pack('<III', 1, 0, 0)) + framelist + geomlist + atomic + chunk(0x03, b''))

    # absolute offsets inside the clump for the DLL
    geom_struct_payload = clump.index(geom_struct) + 12
    prelit_off = geom_struct_payload + prelit_off_in_g
    matcol_off = clump.index(chunk(0x01, mat_struct)) + 12 + 4
    return clump, prelit_off, matcol_off, nv, shade


def main():
    dff, prelit_off, matcol_off, nv, shade = build()
    assert len(dff) <= 2048, len(dff)          # must fit in the one IMG sector the effect models occupy
    lines = ['/* Generated by tools/gen_marker.py - do not edit. */', '#pragma once', '',
             f'#define MARKER_DFF_SIZE      {len(dff)}',
             f'#define MARKER_PRELIT_OFFSET {prelit_off}',
             f'#define MARKER_MATCOL_OFFSET {matcol_off}',
             f'#define MARKER_VERTS         {nv}', '',
             'static const unsigned char marker_shade[MARKER_VERTS] = {',
             '    ' + ', '.join(str(s) for s in shade), '};', '',
             'static const unsigned char marker_dff[MARKER_DFF_SIZE] = {']
    for i in range(0, len(dff), 16):
        lines.append('    ' + ', '.join(f'0x{c:02x}' for c in dff[i:i + 16]) + ',')
    lines.append('};')
    with open(OUT, 'w', newline='\n') as fh:
        fh.write('\n'.join(lines) + '\n')
    print(f'{OUT}: {len(dff)} bytes, {nv} verts, prelit@{prelit_off}, matcol@{matcol_off}')


if __name__ == '__main__':
    main()
